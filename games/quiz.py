QUESTIONS_PER_GAME = 5
MAX_EXTRA = 3


def _math_question() -> dict:
    a, b = rng.randint(6, 49), rng.randint(3, 29)
    op = rng.choice(("+", "-", "×"))
    ans = a + b if op == "+" else (a - b if op == "-" else a * b)
    wrong = set()
    while len(wrong) < 3:
        w = ans + rng.choice((-1, 1)) * rng.randint(1, 12)
        if w != ans:
            wrong.add(w)
    opts = [ans] + list(wrong)
    rng.shuffle(opts)
    return {"q": f"حاصل {a} {op} {b} چند است؟", "opts": [str(x) for x in opts], "ans": opts.index(ans)}


def make_question(exclude=()) -> dict:
    """سوال تصادفی با گزینه‌های shuffle‌شده"""
    if rng.random() < 0.15:
        return _math_question()
    pool = [r for r in _RAW if r[0] not in exclude] or _RAW
    r = rng.choice(pool)
    opts = list(r[1:])
    rng.shuffle(opts)
    return {"q": r[0], "opts": opts, "ans": opts.index(r[1])}


get_random_q = make_question


async def miniapp_init(g):
    a, b = g.uids()
    used = set()
    qs = []
    for _ in range(QUESTIONS_PER_GAME):
        q = make_question(used)
        used.add(q["q"])
        qs.append(q)
    g.data = {"qs": qs, "idx": 0, "answers": {}, "score": {a: 0, b: 0}, "history": [], "extra": 0}
    g.waiting = {a, b}


async def miniapp_action(g, uid, body):
    d = g.data
    if uid not in g.waiting:
        return "به این سوال جواب داده‌ای — منتظر حریف باش"
    try:
        ans = int(body.get("answer"))
    except (TypeError, ValueError):
        return "گزینه نامعتبر است"
    q = d["qs"][d["idx"]]
    if not 0 <= ans < len(q["opts"]):
        return "گزینه نامعتبر است"
    d["answers"][uid] = ans
    g.waiting.discard(uid)
    if g.waiting:
        return None
    a, b = g.uids()
    for u in (a, b):
        if d["answers"][u] == q["ans"]:
            d["score"][u] += 1
    d["history"].append({"q": q, "answers": dict(d["answers"])})
    d["answers"] = {}
    d["idx"] += 1
    if d["idx"] >= len(d["qs"]):
        if d["score"][a] != d["score"][b]:
            w = a if d["score"][a] > d["score"][b] else b
            g.finish(w, f"{g.name(w)} با {d['score'][w]} جواب درست برد")
            return None
        if d["extra"] >= MAX_EXTRA:
            g.finish(None, "امتیازها برابر ماند — مساوی")
            return None
        d["extra"] += 1
        d["qs"].append(make_question({x["q"] for x in d["qs"]}))
    g.waiting = {a, b}
    return None


def miniapp_view(g, uid) -> dict:
    d = g.data
    o = g.opp(uid)
    cur = d["qs"][d["idx"]] if d["idx"] < len(d["qs"]) else None
    last = None
    if d["history"]:
        h = d["history"][-1]
        last = {"q": h["q"]["q"], "opts": h["q"]["opts"], "correct": h["q"]["ans"],
                "mine": h["answers"].get(uid), "opp": h["answers"].get(o)}
    return {"idx": d["idx"], "total": len(d["qs"]), "sudden": d["idx"] >= QUESTIONS_PER_GAME,
            "question": {"q": cur["q"], "opts": cur["opts"]} if cur and not g.finished else None,
            "my_answer": d["answers"].get(uid), "opp_answered": o in d["answers"],
            "score_me": d["score"][uid], "score_opp": d["score"][o], "last": last}


MINIAPP_GAMES = {"quiz": {"init": miniapp_init, "action": miniapp_action, "view": miniapp_view}}

